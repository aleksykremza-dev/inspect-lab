"""Download the public attack datasets into data/raw/ (gitignored).

Nothing here is written by hand: the files are the published datasets with their own licenses (see SOURCES.md).
"""
import json
import subprocess
import sys
import urllib.request
from pathlib import Path

RAW = Path(__file__).parent / "raw"

HF_DATASETS = {
    # name -> (hub id, license)
    "deepset_prompt_injections": ("deepset/prompt-injections", "Apache-2.0"),
    "lakera_gandalf_ignore_instructions": ("Lakera/gandalf_ignore_instructions", "MIT"),
}
RAW_FILES = {
    "cyberseceval2_prompt_injection.json": (
        "https://raw.githubusercontent.com/meta-llama/PurpleLlama/main/CybersecurityBenchmarks/datasets/prompt_injection/prompt_injection.json",
        "MIT",
    ),
}
GIT_REPOS = {
    "BIPIA": ("https://github.com/microsoft/BIPIA.git", "MIT"),
}


def fetch_hf() -> None:
    from datasets import load_dataset
    for name, (hub_id, _lic) in HF_DATASETS.items():
        out = RAW / f"{name}.jsonl"
        if out.exists():
            print(f"skip {name}: exists")
            continue
        ds = load_dataset(hub_id)
        rows = 0
        with open(out, "w", encoding="utf-8") as handle:
            for split in ds:
                for row in ds[split]:
                    handle.write(json.dumps({"split": split, **row}, ensure_ascii=False) + "\n")
                    rows += 1
        print(f"{name}: {rows} rows -> {out.name}")


def fetch_raw() -> None:
    for name, (url, _lic) in RAW_FILES.items():
        out = RAW / name
        if out.exists():
            print(f"skip {name}: exists")
            continue
        urllib.request.urlretrieve(url, out)
        print(f"{name}: {out.stat().st_size} bytes")


def fetch_git() -> None:
    for name, (url, _lic) in GIT_REPOS.items():
        out = RAW / name
        if out.exists():
            print(f"skip {name}: exists")
            continue
        subprocess.run(["git", "clone", "--depth", "1", "-q", url, str(out)], check=True)
        print(f"{name}: cloned")


def write_sources() -> None:
    lines = ["# Dataset sources and licenses (auto-generated by data/fetch.py)", "",
             "| Dataset | Source | License |", "|---|---|---|"]
    for name, (hub_id, lic) in HF_DATASETS.items():
        lines.append(f"| {name} | https://huggingface.co/datasets/{hub_id} | {lic} |")
    for name, (url, lic) in RAW_FILES.items():
        lines.append(f"| {name} | {url} | {lic} |")
    for name, (url, lic) in GIT_REPOS.items():
        lines.append(f"| {name} | {url} | {lic} |")
    (RAW.parent / "SOURCES.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    RAW.mkdir(parents=True, exist_ok=True)
    fetch_raw()
    fetch_hf()
    fetch_git()
    write_sources()
    return 0


if __name__ == "__main__":
    sys.exit(main())
